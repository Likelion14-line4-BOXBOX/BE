-- H2 댓글 테스트 전용 보강이다. 운영 MySQL 전체 스키마는 변경하지 않는다.
ALTER TABLE comments ALTER COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
-- H2의 UTF-16 길이 계산 차이: 실제 VARCHAR(1000)의 이모지 경계는 MySQL에서 검증한다.
ALTER TABLE comments ALTER COLUMN content VARCHAR(4000);
ALTER TABLE comments ADD UNIQUE (post_id,id);
ALTER TABLE comments ADD FOREIGN KEY (post_id,parent_id) REFERENCES comments(post_id,id);
ALTER TABLE comments ADD CHECK (deleted_at IS NOT NULL OR (content IS NOT NULL AND CHAR_LENGTH(TRIM(content))>0));
CREATE TABLE comment_likes (
    comment_id BIGINT REFERENCES comments(id), user_id BIGINT REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(comment_id,user_id)
);
